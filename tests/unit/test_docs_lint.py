def _load_claims() -> list[dict]:
    claims = yaml.safe_load((LINT_DIR / "kg_claims.yaml").read_text(encoding="utf-8"))
    assert isinstance(claims, list) and claims
    return claims


def test_kg_claims_register_is_well_formed():
    claims = _load_claims()
    ids = [c["id"] for c in claims]
    assert len(set(ids)) == len(ids), "duplicate claim id"
    for c in claims:
        assert {"id", "expect", "used_in"} <= set(c), c["id"]
        assert c.get("cypher") or c.get("source"), f"{c['id']}: needs cypher or source"
        assert isinstance(c["expect"], dict) and c["expect"], c["id"]
        tol = c.get("tolerance") or {}
        assert set(tol) <= {"abs", "rel"}, f"{c['id']}: tolerance keys must be abs/rel"


@pytest.mark.parametrize("claim", _load_claims(), ids=lambda c: c["id"])
def test_kg_claims_used_in_exist(claim: dict):
    missing = [p for p in claim["used_in"] if not (REPO / p).exists()]
    assert not missing, f"{claim['id']}: used_in paths do not exist: {missing}"


# ---------------------------------------------------------------------------
# 5. CLAUDE.md tool table stays a routing table
# ---------------------------------------------------------------------------

CLAUDE_ROW_MAX_CHARS = 700
_SPEC_REF_RE = re.compile(r"§")
_CONFIG_INTERNALS_RE = re.compile(r"\b(?:term_verbose|term_details_compact|bridges_out|hierarchy_rels)\b")
_CHANGELOG_RE = re.compile(r"\b(?:removed|successor of|renamed from|superseded by)\b", re.I)
_FOOTNOTE_RE = re.compile(r"`?\[(?:AQ|ENR|TRUST)\]`?")


@pytest.fixture(scope="module")
def claude_rows() -> dict[str, str]:
    rows = claude_md_rows()
    assert rows, "no tool-table rows parsed from CLAUDE.md"
    return rows


def test_claude_md_table_row_length(claude_rows):
    long = {t: len(r) for t, r in claude_rows.items() if len(r) > CLAUDE_ROW_MAX_CHARS}
    assert not long, (
        f"CLAUDE.md rows over {CLAUDE_ROW_MAX_CHARS} chars (move detail to docs://tools/<name>):\n  "
        + "\n  ".join(f"{t}: {n}" for t, n in sorted(long.items(), key=lambda kv: -kv[1]))
    )


def test_claude_md_table_no_spec_refs(claude_rows):
    bad = [t for t, r in claude_rows.items() if _SPEC_REF_RE.search(r)]
    assert not bad, f"CLAUDE.md rows cite spec sections (§): {bad}"


def test_claude_md_table_no_config_internals(claude_rows):
    bad = {t: sorted(set(_CONFIG_INTERNALS_RE.findall(r))) for t, r in claude_rows.items()
           if _CONFIG_INTERNALS_RE.search(r)}
    assert not bad, f"CLAUDE.md rows leak ONTOLOGY_CONFIG internals: {bad}"


def test_claude_md_table_no_changelog_words(claude_rows):
    bad = {}
    for t, r in claude_rows.items():
        body = _FOOTNOTE_RE.sub("", r)
        words = sorted(set(w.lower() for w in _CHANGELOG_RE.findall(body)))
        if words:
            bad[t] = words
    assert not bad, (
        "CLAUDE.md rows carry changelog language (what a field replaced belongs in CHANGELOG.md):\n  "
        + "\n  ".join(f"{t}: {w}" for t, w in bad.items())
    )


# ---------------------------------------------------------------------------
# 6. Tool inventory consistent across every surface
# ---------------------------------------------------------------------------

# Tools that start_here.md is allowed not to mention. Keep empty; add a name
# only with a reason.
START_HERE_EXEMPT: set[str] = set()


def _expected_tools_constant() -> set[str]:
    src = (REPO / "tests" / "unit" / "test_tool_wrappers.py").read_text(encoding="utf-8")
    m = re.search(r"EXPECTED_TOOLS\s*=\s*\[(.*?)\]", src, re.S)
    assert m, "EXPECTED_TOOLS not found in tests/unit/test_tool_wrappers.py"
    return set(re.findall(r'"(\w+)"', m.group(1)))


def _inventory() -> dict[str, set[str]]:
    registry = registered_tool_names()
    return {
        "tools.py @mcp.tool": registry,
        "test_tool_wrappers.EXPECTED_TOOLS": _expected_tools_constant(),
        "references/tools/*.md": {p.stem for p in (REFS / "tools").glob("*.md")},
        "inputs/tools/*.yaml": {p.stem for p in (INPUTS / "tools").glob("*.yaml")},
        "CLAUDE.md table": set(claude_md_rows()),
    }


def test_tool_inventory_consistent():
    sets = _inventory()
    universe = set().union(*sets.values())
    problems = []
    for name in sorted(universe):
        missing = [k for k, v in sets.items() if name not in v]
        if missing:
            problems.append(f"{name}: missing from {missing}")
    assert not problems, "tool inventory drift:\n  " + "\n  ".join(problems)


def test_tool_inventory_start_here_mentions_every_tool():
    registry = registered_tool_names()
    text = START_HERE.read_text(encoding="utf-8")
    mentioned = {t for t in re.findall(r"`(\w+)`", text) if t in registry}
    missing = sorted(registry - mentioned - START_HERE_EXEMPT)
    assert not missing, f"start_here.md never mentions: {missing}"
    stale_exempt = sorted(START_HERE_EXEMPT & mentioned)
    assert not stale_exempt, f"START_HERE_EXEMPT entries now mentioned — drop them: {stale_exempt}"


def test_tool_inventory_count_claims_in_claude_md_and_readme():
    """'N tools' in CLAUDE.md / examples README / analysis docs equals the registry.

    tests/unit/test_about_content.py::test_tool_count_claims_match_registry
    already covers guide/*.md and server.py; this extends the same rule to the
    remaining surfaces and to the kg_claims register's tool_count entry.
    """
    total = len(registered_tool_names())
    files = [CLAUDE_MD, EXAMPLES_DIR / "README.md"] + sorted((REFS / "analysis").glob("*.md")) \
        + sorted((REFS / "ontologies").glob("*.md"))
    bad = []
    for f in files:
        for i, line in enumerate(_lines(f), 1):
            for n in re.findall(r"\b(\d+)\s+tools\b", line):
                # small counts ("the 7 chemistry tools") are sub-family sizes,
                # not inventory claims
                if int(n) >= 30 and int(n) != total:
                    bad.append(f"{_rel(f)}:{i}: '{n} tools' (registry has {total})")
    for c in _load_claims():
        if c.get("source") == "tool_registry" and c["expect"].get("tools") != total:
            bad.append(f"inputs/lint/kg_claims.yaml: {c['id']} expects {c['expect']} (registry has {total})")
    assert not bad, "tool-count claim drift:\n  " + "\n  ".join(bad)


