# 2. Stale identifiers
# ---------------------------------------------------------------------------

def _load_stale_rules() -> list[dict]:
    rules = yaml.safe_load((LINT_DIR / "stale_identifiers.yaml").read_text(encoding="utf-8"))
    assert isinstance(rules, list) and rules
    for r in rules:
        assert {"pattern", "reason", "replacement"} <= set(r), r
        r["_re"] = re.compile(r["pattern"])
        r["_allow_in"] = re.compile(r["allow_in"]) if r.get("allow_in") else None
        r["_near"] = re.compile(r["near"]) if r.get("near") else None
    return rules


def _stale_hits(path: Path, rules: list[dict]) -> list[str]:
    rel = _rel(path)
    lines = _lines(path)
    hits = []
    for rule in rules:
        if any(fnmatch(rel, g) for g in rule.get("allow_files", []) or []):
            continue
        window = int(rule.get("near_lines", 3))
        for i, line in enumerate(lines):
            if not rule["_re"].search(line):
                continue
            if rule["_allow_in"] and rule["_allow_in"].search(line):
                continue
            if rule["_near"]:
                ctx = "\n".join(lines[max(0, i - window): i + window + 1])
                if not rule["_near"].search(ctx):
                    continue
            hits.append(
                f"{i + 1}: /{rule['pattern']}/ — {rule['reason']}; "
                f"use: {rule['replacement']}\n      {line.strip()[:140]}"
            )
    return hits


def test_stale_rules_file_is_well_formed():
    rules = _load_stale_rules()
    assert len({r["pattern"] for r in rules}) == len(rules), "duplicate pattern"


@pytest.mark.parametrize("path", DOC_FILES, ids=_rel)
def test_no_stale_identifiers(path: Path):
    hits = _stale_hits(path, _load_stale_rules())
    assert not hits, f"{_rel(path)}: stale identifiers\n  " + "\n  ".join(hits)


# ---------------------------------------------------------------------------
# 3. Vocabulary values quoted in docs are live
# ---------------------------------------------------------------------------

# Docs-side context keyword -> snapshot property. Both `treatment_type` and
# `treatment_types` (gene_response_profile) map to the same vocabulary.
_VOCAB_CONTEXTS = {
    "treatment[_ ]types?": "treatment_type",
    "background[_ ]factors": "background_factors",
    "compartments?": "compartment",
}
# `kw=['a', 'b']`, `kw: "a"`, `kw (e.g. ['a', 'b'])`, `kw="a"`
_VOCAB_ASSIGN_RE = (
    r"\b(?P<kw>{kw})\b[^\n]{{0,60}}?"
    r"(?:[:=]|\(e\.g\.|e\.g\.)\s*(?P<val>\[[^\]\n]*\]|['\"][a-z_]+['\"])"
)
_IN_TREATMENT_RE = re.compile(r"['\"]([a-z_]+)['\"]\s+IN\s+\w+\.(treatment_type|background_factors)\b")
_QUOTED_RE = re.compile(r"['\"]([a-z_]+)['\"]")
# Documentation placeholders, not values: `'value' IN e.treatment_type`.
_VOCAB_PLACEHOLDERS = {
    "value", "values",
    # kg_schema payloads render property TYPES in the same "key": "type" shape
    "list", "string", "integer", "float", "boolean", "str", "int", "bool", "array", "object", "null",
}


def _load_vocab_snapshot() -> dict[str, set[str]]:
    snap = yaml.safe_load((LINT_DIR / "vocab_snapshot.yaml").read_text(encoding="utf-8"))
    out: dict[str, set[str]] = {}
    for prop, by_applies in snap["vocabularies"].items():
        out[prop] = set().union(*(set(v["values"]) for v in by_applies.values()))
    return out


def _vocab_hits(path: Path, vocab: dict[str, set[str]]) -> list[str]:
    hits = []
    for i, line in enumerate(_lines(path), 1):
        for kw_re, prop in _VOCAB_CONTEXTS.items():
            for m in re.finditer(_VOCAB_ASSIGN_RE.format(kw=kw_re), line):
                for val in _QUOTED_RE.findall(m.group("val")):
                    if val not in vocab[prop] and val not in _VOCAB_PLACEHOLDERS:
                        hits.append(f"{i}: {prop}={val!r} is not a live value\n      {line.strip()[:140]}")
        for val, prop in _IN_TREATMENT_RE.findall(line):
            if val not in vocab[prop] and val not in _VOCAB_PLACEHOLDERS:
                hits.append(f"{i}: {prop}={val!r} is not a live value\n      {line.strip()[:140]}")
    return hits


def test_vocab_snapshot_is_well_formed():
    vocab = _load_vocab_snapshot()
    for prop in ("treatment_type", "background_factors", "compartment"):
        assert vocab.get(prop), f"snapshot lacks {prop} — run scripts/snapshot_vocab.py"


@pytest.mark.parametrize("path", DOC_FILES, ids=_rel)
def test_vocab_values_in_docs(path: Path):
    hits = _vocab_hits(path, _load_vocab_snapshot())
    assert not hits, (
        f"{_rel(path)}: quoted vocabulary values not in the KG (snapshot from "
        "inputs/lint/vocab_snapshot.yaml; if the KG changed, run scripts/snapshot_vocab.py)\n  "
        + "\n  ".join(hits)
    )


