"""Mechanical doc-drift lints promoted from the 2026-08 MCP docs review.

Each test encodes one audit that used to be run by hand:

- ``test_docs_links_resolve``       every ``docs://`` URI / ``references/`` path /
                                    relative markdown link resolves against what
                                    server.py actually serves.
- ``test_no_stale_identifiers``     retired identifiers listed in
                                    ``inputs/lint/stale_identifiers.yaml`` do not
                                    appear in user-facing text.
- ``test_vocab_values_in_docs``     every controlled-vocabulary value quoted next
                                    to ``treatment_type`` / ``background_factors``
                                    / ``compartment`` is a live value (offline
                                    snapshot ``inputs/lint/vocab_snapshot.yaml``,
                                    regenerated by ``scripts/snapshot_vocab.py``).
- ``test_kg_claims_used_in_exist``  every ``used_in`` path in
                                    ``inputs/lint/kg_claims.yaml`` exists (the
                                    live evaluation is the ``-m kg`` test in
                                    tests/integration/test_docs_kg_claims.py).
- ``test_claude_md_table_*``        CLAUDE.md tool-table rows stay routing
                                    summaries, not changelog entries.
- ``test_tool_inventory_*``         the tool set is identical across the
                                    registry, docs, YAML, CLAUDE.md, start_here
                                    and the "N tools" claims.

No Neo4j needed. Scanned file set is shared (``DOC_FILES``) so a new surface
only needs adding in one place.
"""

from __future__ import annotations

import ast
import re
from fnmatch import fnmatch
from pathlib import Path

import pytest
import yaml

REPO = Path(__file__).resolve().parents[2]
PKG = REPO / "multiomics_explorer"
REFS = PKG / "skills" / "multiomics-kg-guide" / "references"
INPUTS = PKG / "inputs"
LINT_DIR = INPUTS / "lint"
TOOLS_PY = PKG / "mcp_server" / "tools.py"
SERVER_PY = PKG / "mcp_server" / "server.py"
CLAUDE_MD = REPO / "CLAUDE.md"
EXAMPLES_DIR = REPO / "examples"
START_HERE = REFS / "guide" / "start_here.md"

DOC_FILES: list[Path] = sorted(
    list(REFS.rglob("*.md"))
    + list((INPUTS / "tools").rglob("*.yaml"))
    + list((INPUTS / "ontologies").rglob("*.yaml"))
    + [TOOLS_PY, SERVER_PY, CLAUDE_MD, EXAMPLES_DIR / "README.md"]
    + sorted(EXAMPLES_DIR.glob("*.py"))
)


def _rel(p: Path) -> str:
    return str(p.relative_to(REPO))


def _lines(p: Path) -> list[str]:
    return p.read_text(encoding="utf-8").splitlines()


# ---------------------------------------------------------------------------
# Registry helpers (derived, never hard-coded)
# ---------------------------------------------------------------------------

_TOOL_DECORATOR_RE = re.compile(
    r"@mcp\.tool\((?:[^()]|\([^()]*\))*\)\s*\n\s*(?:async )?def (\w+)\("
)


def registered_tool_names() -> set[str]:
    """Tool function names from ``@mcp.tool(...)`` decorators in tools.py.

    Regex over source (not a FastMCP import) so the lint stays cheap and
    independent of the server lifespan.
    """
    return set(_TOOL_DECORATOR_RE.findall(TOOLS_PY.read_text(encoding="utf-8")))


def served_doc_uris() -> set[str]:
    """Every ``docs://`` URI server.py serves, derived from its own registration
    code: the ``_DOC_DIRS`` globs plus the hard-coded examples list.

    Parsed from source (AST) rather than imported so the test does not build a
    FastMCP app; registering a new example in server.py makes it resolvable
    here automatically.
    """
    tree = ast.parse(SERVER_PY.read_text(encoding="utf-8"))
    uris: set[str] = set()
    doc_dirs: dict[str, str] = {}
    for node in ast.walk(tree):
        # _DOC_DIRS = {"docs://tools": (_SKILLS_DIR / "tools", ...), ...}
        if (
            isinstance(node, ast.Assign)
            and any(isinstance(t, ast.Name) and t.id == "_DOC_DIRS" for t in node.targets)
            and isinstance(node.value, ast.Dict)
        ):
            for k, v in zip(node.value.keys, node.value.values):
                prefix = ast.literal_eval(k)
                # value is a tuple; first element is `_SKILLS_DIR / "<sub>"`
                sub = v.elts[0].right if isinstance(v, ast.Tuple) else None
                doc_dirs[prefix] = ast.literal_eval(sub)
        # `for example_name, example_description in [("x.py", "..."), ...]:`
        if isinstance(node, ast.For) and isinstance(node.iter, ast.List):
            for elt in node.iter.elts:
                if isinstance(elt, ast.Tuple) and elt.elts:
                    try:
                        name = ast.literal_eval(elt.elts[0])
                    except ValueError:
                        continue
                    if isinstance(name, str) and name.endswith(".py"):
                        uris.add(f"docs://examples/{name}")
    assert doc_dirs, "could not parse _DOC_DIRS from server.py"
    for prefix, sub in doc_dirs.items():
        for md in (REFS / sub).glob("*.md"):
            uris.add(f"{prefix}/{md.stem}")
    return uris


def claude_md_rows() -> dict[str, str]:
    """``{tool_name: row_body}`` for every row of the CLAUDE.md tool table."""
    rows = {}
    for line in _lines(CLAUDE_MD):
        m = re.match(r"^\| `(\w+)` \|(.*)\|\s*$", line)
        if m:
            rows[m.group(1)] = m.group(2).strip()
    return rows


# ---------------------------------------------------------------------------
# 1. Links resolve
# ---------------------------------------------------------------------------

_DOCS_URI_RE = re.compile(r"docs://[\w/{}.\-*]+")
_REFS_PATH_RE = re.compile(r"references/[\w/.\-]+")
_MD_LINK_RE = re.compile(r"\[([^\]]*)\]\(([^)\s]+)\)")
_TRAILING = ".,;:)`'\"*"


@pytest.mark.parametrize("path", DOC_FILES, ids=_rel)
def test_docs_links_resolve(path: Path):
    served = served_doc_uris()
    prefixes = {u.rsplit("/", 1)[0] for u in served}
    bad = []
    for i, line in enumerate(_lines(path), 1):
        for u in _DOCS_URI_RE.findall(line):
            u = u.rstrip(_TRAILING)
            if "{" in u or "*" in u:  # templated / glob form: docs://tools/{name}, docs://analysis/*
                continue
            if u.endswith("/") and u[:-1] in prefixes:  # "docs://analysis/ pages"
                continue
            if path == SERVER_PY and u in prefixes:  # the _DOC_DIRS registration keys themselves
                continue
            if u not in served:
                bad.append(f"{i}: unresolved doc URI {u}")
        for u in _REFS_PATH_RE.findall(line):
            u = u.rstrip(_TRAILING)
            if "{" in u or "*" in u:
                continue
            candidate = REFS.parent / u
            if not candidate.exists() and not (REFS / u[len("references/"):]).exists():
                bad.append(f"{i}: unresolved references/ path {u}")
        if path.suffix == ".md":
            for _txt, u in _MD_LINK_RE.findall(line):
                if u.startswith(("http://", "https://", "docs://", "#", "mailto:")):
                    continue
                if "/" not in u and "." not in u:  # `[C@H](O)` in a SMILES string is not a link
                    continue
                target = (path.parent / u.split("#", 1)[0]).resolve()
                if not target.exists():
                    bad.append(f"{i}: broken relative link {u}")
    assert not bad, f"{_rel(path)}:\n  " + "\n  ".join(bad)


